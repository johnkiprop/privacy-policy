"""Generate GitHub Pages-compatible, script-free policy pages from local JSON."""
import argparse
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "_locales"
EMAIL = "admin@maonoautonomous.com"
EXPECTED = ("en", "sw", "es", "fr", "de", "pt", "ar", "hi", "zh-Hans",
            "zh-Hant", "bn", "ur", "id", "ru", "ja", "ko", "tr", "vi")
SECTIONS = ("scope", "visibility", "permissions", "storage", "retention", "deletion",
            "network", "actions", "operator", "website", "contact")
FIELDS = {"title", "description", "skip", "languages", "effective", "contact",
          "contents", "draft", "sections"}


def load():
    manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
    assert tuple(item["code"] for item in manifest["locales"]) == EXPECTED
    data = {}
    for locale in manifest["locales"]:
        code = locale["code"]
        text = json.loads((SOURCE / f"{code}.json").read_text(encoding="utf-8"))
        assert set(text) == FIELDS, f"{code}: missing or extra keys"
        assert tuple(text["sections"]) == SECTIONS, f"{code}: wrong sections"
        assert locale["dir"] == ("rtl" if code in ("ar", "ur") else "ltr")
        for key, value in text.items():
            if key != "sections":
                assert isinstance(value, str) and value.strip(), f"{code}/{key}"
        for key, pair in text["sections"].items():
            assert isinstance(pair, list) and len(pair) == 2, f"{code}/{key}"
            assert all(isinstance(s, str) and s.strip() for s in pair), f"{code}/{key}"
            if code != "en":
                english = data["en"]["sections"][key]
                assert all(a != b for a, b in zip(pair, english)), f"{code}/{key}: English fallback"
        if code != "en":
            assert all(text[k] != data["en"][k] for k in FIELDS - {"sections"}), code
        data[code] = text
    return manifest, data


def page_path(code):
    return ROOT / ("index.html" if code == "en" else f"{code}/index.html")


def render(locale, text, manifest):
    e = html.escape
    code = locale["code"]
    prefix = "" if code == "en" else "../"
    links = []
    for other in manifest["locales"]:
        dest = "index.html" if other["code"] == "en" else f'{other["code"]}/index.html'
        current = ' aria-current="page"' if code == other["code"] else ""
        links.append(f'<li><a href="{prefix}{dest}" lang="{other["code"]}" '
                     f'hreflang="{other["code"]}" dir="{other["dir"]}"{current}>'
                     f'{e(other["name"])}</a></li>')
    contents = "\n".join(f'<li><a href="#{key}">{e(pair[0])}</a></li>'
                         for key, pair in text["sections"].items())
    sections = []
    for key, pair in text["sections"].items():
        body = e(pair[1]).replace("10.0.0.1/32", '<bdi dir="ltr">10.0.0.1/32</bdi>')
        sections.append(f'<section aria-labelledby="{key}"><h2 id="{key}">{e(pair[0])}</h2>'
                        f'<p>{body}</p></section>')
    sections = "\n".join(sections)
    return f'''<!doctype html>
<!-- Generated by _tools/build.py. Edit _locales JSON, not this file. -->
<html lang="{code}" dir="{locale["dir"]}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<title>{e(text["title"])}</title>
<meta name="description" content="{e(text["description"])}">
<link rel="stylesheet" href="{prefix}assets/policy.css">
</head>
<body>
<a class="skip" href="#policy">{e(text["skip"])}</a>
<header><div class="wrap">
<h1>{e(text["title"])}</h1>
<p>{e(text["effective"])}: <time dir="ltr" datetime="{manifest["effective_date"]}">{manifest["effective_date"]}</time></p>
<details id="language-picker"><summary>{e(text["languages"])}</summary>
<nav aria-label="{e(text["languages"])}"><ul class="languages">
{chr(10).join(links)}
</ul></nav></details>
</div></header>
<main id="policy" class="wrap" tabindex="-1">
<p class="draft">{e(text["draft"])}</p>
<nav class="contents" aria-label="{e(text["contents"])}"><ol>
{contents}
</ol></nav>
{sections}
</main>
<footer><div class="wrap">
<a class="email" href="mailto:{EMAIL}">{e(text["contact"])}: <bdi dir="ltr">{EMAIL}</bdi></a>
</div></footer>
</body>
</html>
'''


def build(check=False):
    manifest, data = load()
    for locale in manifest["locales"]:
        path = page_path(locale["code"])
        output = render(locale, data[locale["code"]], manifest)
        if check:
            assert path.exists() and path.read_text(encoding="utf-8") == output, f"Stale page: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(output, encoding="utf-8", newline="\n")
    return manifest, data


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated pages are stale")
    args = parser.parse_args()
    build(args.check)
    print(f"{len(EXPECTED)} locale pages {'verified' if args.check else 'generated'}.")
